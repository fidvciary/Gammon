const x = new Float64Array(122);

function setx(pos) {
  x.fill(0);
  for (let j = 1; j <= 24; j += 1) {
    const jm1 = j - 1;
    const n = pos[25 - j];
    if (n !== 0) {
      if (n === -1) x[5 * jm1 + 0] = 1.0;
      if (n === 1) x[5 * jm1 + 1] = 1.0;
      if (n >= 2) x[5 * jm1 + 2] = 1.0;
      if (n === 3) x[5 * jm1 + 3] = 1.0;
      if (n >= 4) x[5 * jm1 + 4] = (n - 3) / 2.0;
    }
  }
  x[120] = -pos[0] / 2.0;
  x[121] = pos[26] / 15.0;
}

/**
 * Score a FINAL position (after the candidate move) for the mover.
 * `race` must describe the position BEFORE the move, per Tesauro's notes.
 * Higher is better. Scores are only comparable within one move decision.
 */
export function pubeval(race, pos) {
  if (pos[26] === 15) return 99999999.0;
  setx(pos);
  const w = race ? WR : WC;
  let score = 0.0;
  for (let i = 0; i < 122; i += 1) score += w[i] * x[i];
  return score;
}
